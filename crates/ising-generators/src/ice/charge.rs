/// The sizes of an instance: the topology itself.
fn charged_ice_size_bounds(_: &Params<'_>, stats: &TopologyStats) -> Result<SizeBounds, Code> {
    if stats.max_degree > MAX_DEGREE {
        return Err(Code::BoundsExceeded);
    }
    Ok(SizeBounds {
        nodes: stats.n_nodes,
        edges: stats.n_edges,
        degree: stats.max_degree,
    })
}

/// The lattice the parameters name.
fn lattice(params: &Params<'_>) -> Result<Lattice, StructureError> {
    let m = match params.get(TAG_M) {
        Some(Value::Unsigned(m)) => u16::try_from(m).ok(),
        _ => None,
    };
    let t = match params.get(TAG_T) {
        Some(Value::Unsigned(t)) => u8::try_from(t).ok(),
        _ => None,
    };
    match (m, t) {
        (Some(m), Some(t)) => Lattice::from_shape(m, t),
        _ => Err(StructureError::Overflow),
    }
}

/// An unsigned parameter as an `i32`, `None` when missing or out of range.
fn milli(params: &Params<'_>, tag: u16) -> Option<i32> {
    match params.get(tag) {
        Some(Value::Unsigned(value)) => i32::try_from(value).ok(),
        _ => None,
    }
}

/// The charged-tile chance in 256ths, `None` when missing or out of range.
fn charged_per_256(params: &Params<'_>) -> Option<u32> {
    match params.get(TAG_CHARGED) {
        Some(Value::Unsigned(chance)) => u32::try_from(chance).ok(),
        _ => None,
    }
}

/// Admission: the parameters name a lattice and the topology carries tiles.
/// A degree above the limit is left to the size bounds (code 13).
fn check_topology(params: &Params<'_>, topology: &BaseTopology) -> bool {
    let Ok(lattice) = lattice(params) else {
        return false;
    };
    match candidates(lattice, topology) {
        Ok(_) | Err(StructureError::DegreeAboveLimit) => true,
        Err(_) => false,
    }
}

/// The six edges of a tile with their couplings under the tile's own gauge:
/// `scale * g[a] * g[b]`. `None` when the arithmetic overflows.
fn tile_couplings(nodes: [u32; 4], gauge: [i8; 4], scale: i32) -> Option<[((u32, u32), i32); 6]> {
    let [a, b, c, d] = nodes;
    let [ga, gb, gc, gd] = gauge;
    let coupling = |x: i8, y: i8| scale.checked_mul(i32::from(x))?.checked_mul(i32::from(y));
    Some([
        ((a, b), coupling(ga, gb)?),
        ((a, c), coupling(ga, gc)?),
        ((a, d), coupling(ga, gd)?),
        ((b, c), coupling(gb, gc)?),
        ((b, d), coupling(gb, gd)?),
        ((c, d), coupling(gc, gd)?),
    ])
}

/// The expected fields: `h[i] = sum over tiles of -scale * q * g[i]` and the
/// offset `sum over tiles of scale * (4 + q^2) / 2`. `None` when a position is
/// out of range or the arithmetic overflows.
fn expected_fields(
    tiles: &[[u32; 4]],
    gauges: &[[i8; 4]],
    charges: &[i8],
    scale: i32,
    n: usize,
) -> Option<(Vec<i32>, i64)> {
    let scale = i64::from(scale);
    let mut h = vec![0_i64; n];
    let mut offset = 0_i64;
    for ((tile, gauge), &charge) in tiles.iter().zip(gauges).zip(charges) {
        let q = i64::from(charge);
        for (&pos, &g) in tile.iter().zip(gauge) {
            let field = h.get_mut(usize::try_from(pos).ok()?)?;
            let term = scale.checked_mul(q)?.checked_mul(i64::from(g))?;
            *field = field.checked_sub(term)?;
        }
        let penalty = scale.checked_mul(q.checked_mul(q)?.checked_add(4)?)? / 2;
        offset = offset.checked_add(penalty)?;
    }
    let h = h
        .into_iter()
        .map(|field| i32::try_from(field).ok())
        .collect::<Option<Vec<i32>>>()?;
    Some((h, offset))
}

fn generate(
    params: &Params<'_>,
    topology: &BaseTopology,
    streams: &mut Streams<'_>,
) -> Result<InstanceBody, Code> {
    let defect = Code::TopologyIncompatible;
    let scale = milli(params, TAG_SCALE).ok_or(Code::ParamsMalformed)?;
    let background = milli(params, TAG_BACKGROUND).ok_or(Code::ParamsMalformed)?;
    let chance = charged_per_256(params).ok_or(Code::ParamsMalformed)?;
    let lattice = lattice(params).map_err(|_| defect)?;
    let tiles = select_tiles(lattice, topology, streams, LEFT, RIGHT)?;

    let two = NonZeroU32::MIN.saturating_add(1);
    let of_256 = NonZeroU32::MIN.saturating_add(255);
    let mut charge_stream = streams.open(CHARGE).ok_or(Code::NoInstance)?;
    let mut charges: Vec<i8> = Vec::with_capacity(tiles.len());
    for _ in &tiles {
        let draw = uniform(&mut charge_stream, of_256);
        let sign = uniform(&mut charge_stream, two);
        charges.push(if draw >= chance {
            0
        } else if sign == 0 {
            CHARGE_UNIT
        } else {
            -CHARGE_UNIT
        });
    }

    let mut gauge_stream = streams.open(GAUGE).ok_or(Code::NoInstance)?;
    let gauges: Vec<[i8; 4]> = tiles
        .iter()
        .map(|_| {
            [(); 4].map(|()| {
                if uniform(&mut gauge_stream, two) == 0 {
                    1
                } else {
                    -1
                }
            })
        })
        .collect();

    let node_ids = topology.node_ids().to_vec();
    let edges = sorted_edges(topology);
    let mut fixed: Vec<Option<i32>> = vec![None; edges.len()];
    let tile_nodes: Vec<[u32; 4]> = tiles.iter().map(|tile| tile.nodes).collect();
    for (tile, gauge) in tile_nodes.iter().zip(&gauges) {
        for (pair, coupling) in tile_couplings(*tile, *gauge, scale).ok_or(Code::BoundsExceeded)? {
            let at = edges.binary_search(&pair).map_err(|_| defect)?;
            *fixed.get_mut(at).ok_or(defect)? = Some(coupling);
        }
    }

    let mut background_stream = streams.open(BACKGROUND).ok_or(Code::NoInstance)?;
    let mut j: Vec<i32> = Vec::with_capacity(edges.len());
    for coupling in &fixed {
        j.push(match coupling {
            Some(coupling) => *coupling,
            None if uniform(&mut background_stream, two) == 0 => background,
            None => -background,
        });
    }

    let (h, offset_milli) = expected_fields(&tile_nodes, &gauges, &charges, scale, node_ids.len())
        .ok_or(Code::BoundsExceeded)?;
    let metadata = region(&[
        (KIND_TILES, tiles_payload(&tiles)?),
        (KIND_GAUGES, gauges_payload(&gauges)?),
        (KIND_CHARGES, charges_payload(&charges)?),
    ])?;
    Ok(InstanceBody {
        node_ids,
        edges,
        h,
        j,
        offset_milli,
        metadata,
    })
}

/// The payload of tile charges: the tile count, then one `i8` byte per tile.
fn charges_payload(charges: &[i8]) -> Result<Vec<u8>, Code> {
    let mut payload = u32::try_from(charges.len())
        .map_err(|_| Code::BoundsExceeded)?
        .to_le_bytes()
        .to_vec();
    payload.extend(charges.iter().map(|&q| q.to_le_bytes()[0]));
    Ok(payload)
}

/// The charges of a kind 6 payload: one byte per tile, each `0`, `2`, or `-2`.
fn parse_charges(payload: &[u8], tiles: usize) -> Option<Vec<i8>> {
    let mut reader = Reader::new(payload);
    let count = usize::try_from(reader.u32()?).ok()?;
    if count != tiles || reader.rest().len() != count {
        return None;
    }
    reader
        .rest()
        .iter()
        .map(|&byte| {
            let charge = i8::from_le_bytes([byte]);
            [0, CHARGE_UNIT, -CHARGE_UNIT]
                .contains(&charge)
                .then_some(charge)
        })
        .collect()
}

/// The tiles, gauges, and charges of an instance region.
type Decoded = (Vec<[u32; 4]>, Vec<[i8; 4]>, Vec<i8>);

/// Decode the three metadata sections of `instance`.
fn decode(instance: &Instance) -> Option<Decoded> {
    let n = instance.node_ids().len();
    let [tile_payload, gauge_payload, charge_payload] =
        sections(instance.metadata(), [KIND_TILES, KIND_GAUGES, KIND_CHARGES])?;
    let tiles = parse_tiles(tile_payload, n)?;
    let gauges = parse_gauges(gauge_payload, tiles.len())?;
    let charges = parse_charges(charge_payload, tiles.len())?;
    Some((tiles, gauges, charges))
}

fn check_metadata(params: &Params<'_>, instance: &Instance) -> bool {
    check_instance(params, instance).is_some()
}

/// `Some` when the instance is a valid charged-ice instance.
fn check_instance(params: &Params<'_>, instance: &Instance) -> Option<()> {
    let scale = milli(params, TAG_SCALE)?;
    let background = milli(params, TAG_BACKGROUND)?;
    let n = instance.node_ids().len();
    let (tiles, gauges, charges) = decode(instance)?;
    let edges = instance.edges();
    let js = instance.j();
    if js.len() != edges.len() {
        return None;
    }

    let (want_h, want_offset) = expected_fields(&tiles, &gauges, &charges, scale, n)?;
    if instance.h() != want_h.as_slice() || instance.offset_milli() != want_offset {
        return None;
    }

    let is_tile = mark_tiles(&tiles, edges, n)?;
    for (tile, gauge) in tiles.iter().zip(&gauges) {
        for (pair, coupling) in tile_couplings(*tile, *gauge, scale)? {
            let at = edges.binary_search(&pair).ok()?;
            if *js.get(at)? != coupling {
                return None;
            }
        }
    }
    for (&flagged, &coupling) in is_tile.iter().zip(js) {
        if !flagged && coupling != background && coupling != -background {
            return None;
        }
    }
    Some(())
}

/// Tiles whose charge `sum g_i s_i` differs from `q_t`, for a spin state of the
/// instance. `None` for a malformed instance or a state of the wrong length or
/// with a value other than `+1` or `-1`. This is information only and never
/// part of acceptance.
#[must_use]
pub fn charge_defects(params: &Params<'_>, instance: &Instance, spins: &[i8]) -> Option<u32> {
    let _scale = milli(params, TAG_SCALE)?;
    let (tiles, gauges, charges) = decode(instance)?;
    if spins.len() != instance.node_ids().len() || spins.iter().any(|&s| s != 1 && s != -1) {
        return None;
    }
    let mut defects = 0_u32;
    for ((tile, gauge), &charge) in tiles.iter().zip(&gauges).zip(&charges) {
        let mut sum = 0_i32;
        for (&pos, &g) in tile.iter().zip(gauge) {
            let spin = *spins.get(usize::try_from(pos).ok()?)?;
            sum = sum.checked_add(i32::from(g).checked_mul(i32::from(spin))?)?;
        }
        if sum != i32::from(charge) {
            defects = defects.checked_add(1)?;
        }
    }
    Some(defects)
}
