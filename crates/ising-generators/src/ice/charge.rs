//! The `quip/charged-ice` family, revision 1: ice tiles with local gauges and
//! synthetic charges over a weak signed background.
//!
//! The construction picks a set of ice tiles. Each tile carries its own local
//! gauge `g` and a synthetic charge `q` in `{0, +2, -2}`. The penalty
//! `(A / 2) (sum_i g_i s_i - q)^2` is expanded into couplings, fields, and an
//! offset, so the encoded energy equals the direct penalty energy, constant
//! included. Every other edge gets a random coupling of magnitude
//! `background_milli`. The instance keeps every topology edge, and no coupling
//! is zero. The tile charges are synthetic. They do not encode physical vertex
//! charges or link incidence, and the family is not adapted P or D-static.
//! The research cohort is not regenerated by this revision.

