//! The `quip/two-commodity-routing` family, revision 1: native two-commodity
//! unit routing on a Manhattan-street template of Zephyr cells.
//!
//! Every template node is a cell `(c, r)` of the Zephyr grid. Arcs join
//! horizontal and vertical neighbours, with row and column directions that
//! alternate. Commodity 1 uses one spin per arc, shared by the two cells it
//! joins. Commodity 2 uses a two-spin ferromagnetic chain per arc, so the two
//! cells share no commodity 2 spin. The first chain spin crosses the
//! commodity 1 spin of the same arc, and the capacity term sits on that
//! coupler.
//!
//! The template depends on the topology and the parameters only. The
//! terminals and the arc costs depend on the salt. The energy is built in
//! `x = (1 - s) / 2` form with exact quarter-milli integers and then
//! converted to Ising fields, couplings, and an offset.
//!
//! The terminals of the two commodities are checked one at a time with a
//! unit-capacity maximum flow. Two commodities that are each feasible alone
//! need not be feasible together, so the check is not a joint certificate.
//!
//! The research cohort is not regenerated by this revision.

