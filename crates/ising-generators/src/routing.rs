/// The parameters of a revision.
#[derive(Clone, Copy)]
pub(crate) struct Shape {
    pub(crate) m: u16,
    pub(crate) t: u8,
    pub(crate) divisor: usize,
    /// The grid side `L = 2m - 1`.
    pub(crate) side: u16,
}

impl Shape {
    fn of(params: &Params<'_>) -> Option<Self> {
        let m = u16::try_from(unsigned(params, TAG_M)?).ok()?;
        let t = u8::try_from(unsigned(params, TAG_T)?).ok()?;
        let divisor = usize::try_from(unsigned(params, TAG_DIVISOR)?).ok()?;
        let side = m.checked_mul(2)?.checked_sub(1)?;
        (m >= 1 && t >= 1 && divisor >= 1).then_some(Self {
            m,
            t,
            divisor,
            side,
        })
    }
}

/// A grid cell `(c, r)`, ordered by `(c, r)`.
pub(crate) type Cell = (u16, u16);

/// The three lines of one row or column: the commodity 1 line, then the two
/// commodity 2 lines that alternate.
type Triple = [u8; 3];

/// The topology seen through Zephyr coordinates, in dense positions.
pub(crate) struct Grid {
    pub(crate) shape: Shape,
    position: BTreeMap<u32, u32>,
    edges: BTreeSet<(u32, u32)>,
}

impl Grid {
    pub(crate) fn new(shape: Shape, topology: &BaseTopology) -> Self {
        let position = (0u32..)
            .zip(topology.node_ids())
            .map(|(pos, &id)| (id, pos))
            .collect();
        let edges = topology
            .edges()
            .iter()
            .map(|&(u, v)| (u.min(v), u.max(v)))
            .collect();
        Self {
            shape,
            position,
            edges,
        }
    }

    /// The dense position of the segment that starts at position `p` on the
    /// line `(u, w, k)`, `None` when it is not a node of the topology.
    pub(crate) fn seg(&self, u: i64, w: i64, k: u8, p: i64) -> Option<u32> {
        if !(0..2 * i64::from(self.shape.m)).contains(&p) {
            return None;
        }
        let native = zephyr_id(
            self.shape.m,
            self.shape.t,
            [u, w, i64::from(k), p % 2, p / 2],
        )?;
        self.position.get(&native).copied()
    }

    fn linked(&self, a: u32, b: u32) -> bool {
        self.edges.contains(&(a.min(b), a.max(b)))
    }

    /// The four segments of the cell `(c, r)` on the column line `k` and the
    /// row line `k2`: vertical low, vertical high, horizontal left,
    /// horizontal right. Any of them can be missing.
    fn corners(&self, (c, r): Cell, k: u8, k2: u8) -> [Option<u32>; 4] {
        let (c, r) = (i64::from(c), i64::from(r));
        [
            self.seg(0, c, k, r - 1),
            self.seg(0, c, k, r),
            self.seg(1, r, k2, c - 1),
            self.seg(1, r, k2, c),
        ]
    }

    /// Whether the cell K4 exists: four nodes and all six couplers.
    pub(crate) fn has_k4(&self, cell: Cell, k: u8, k2: u8) -> bool {
        let [Some(low), Some(high), Some(left), Some(right)] = self.corners(cell, k, k2) else {
            return false;
        };
        [
            (low, high),
            (low, left),
            (low, right),
            (high, left),
            (high, right),
            (left, right),
        ]
        .iter()
        .all(|&(first, second)| self.linked(first, second))
    }

    /// Whether the cell has both of its K4s for a row triple and a column
    /// triple.
    fn alive(&self, cell: Cell, row: Triple, col: Triple) -> bool {
        let (k, k2) = (col.first(), row.first());
        let (c, r) = cell;
        let (alt_col, alt_row) = (
            col.get(1 + usize::from(r % 2)),
            row.get(1 + usize::from(c % 2)),
        );
        match (k, k2, alt_col, alt_row) {
            (Some(&k), Some(&k2), Some(&alt_col), Some(&alt_row)) => {
                self.has_k4(cell, k, k2) && self.has_k4(cell, alt_col, alt_row)
            }
            _ => false,
        }
    }
}

/// The ordered triples of distinct lines in `0..t`, in lexicographic order.
fn triples(t: u8) -> Vec<Triple> {
    let mut found = Vec::new();
    for a in 0..t {
        for b in 0..t {
            for c in 0..t {
                if a != b && a != c && b != c {
                    found.push([a, b, c]);
                }
            }
        }
    }
    found
}

/// The line triples of every row and column that keep the most cells alive.
/// `rows[r]` and `cols[c]` are indexed by the coordinate, so entry 0 is
/// unused.
fn layout(grid: &Grid) -> Option<(Vec<Triple>, Vec<Triple>)> {
    let side = grid.shape.side;
    let all = triples(grid.shape.t);
    let first = *all.first()?;
    let mut rows = vec![first; usize::from(side) + 1];
    let mut cols = rows.clone();
    loop {
        let mut changed = false;
        for r in 1..=side {
            let score = |row: Triple| -> usize {
                (1..=side)
                    .filter(|&c| {
                        cols.get(usize::from(c))
                            .is_some_and(|&col| grid.alive((c, r), row, col))
                    })
                    .count()
            };
            let current = *rows.get(usize::from(r))?;
            if let Some(best) = best_choice(&all, score(current), score) {
                *rows.get_mut(usize::from(r))? = best;
                changed = true;
            }
        }
        for c in 1..=side {
            let score = |col: Triple| -> usize {
                (1..=side)
                    .filter(|&r| {
                        rows.get(usize::from(r))
                            .is_some_and(|&row| grid.alive((c, r), row, col))
                    })
                    .count()
            };
            let current = *cols.get(usize::from(c))?;
            if let Some(best) = best_choice(&all, score(current), score) {
                *cols.get_mut(usize::from(c))? = best;
                changed = true;
            }
        }
        if !changed {
            return Some((rows, cols));
        }
    }
}

/// The first choice, in order, whose score is the largest and is above
/// `current`. `None` when no choice beats `current`.
pub(crate) fn best_choice<T: Copy>(
    all: &[T],
    current: usize,
    score: impl Fn(T) -> usize,
) -> Option<T> {
    let mut best = current;
    let mut chosen = None;
    for &triple in all {
        let value = score(triple);
        if value > best {
            best = value;
            chosen = Some(triple);
        }
    }
    chosen
}

/// An arc before the strongly connected core: end cells and spins, as dense
/// positions of the topology.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct RawArc {
    tail: Cell,
    head: Cell,
    x1: u32,
    chain: [u32; 2],
}

impl RawArc {
    /// The spin of commodity `k` inside the K4 of the cell `v`.
    fn spin(&self, v: Cell, k: usize) -> u32 {
        if k == 0 {
            self.x1
        } else if v == self.tail.min(self.head) {
            self.chain[0]
        } else {
            self.chain[1]
        }
    }
}

/// Whether `a` is before `b` in cell order.
const fn cell_lt(a: Cell, b: Cell) -> bool {
    a.0 < b.0 || (a.0 == b.0 && a.1 < b.1)
}

/// The arcs of the grid in order: for `c`, then `r` ascending, the
/// horizontal arc, then the vertical arc.
fn raw_arcs(grid: &Grid, rows: &[Triple], cols: &[Triple]) -> Vec<RawArc> {
    let side = grid.shape.side;
    let corners = |cell: Cell, alternate: bool| -> Option<[Option<u32>; 4]> {
        let (c, r) = cell;
        let col = cols.get(usize::from(c))?;
        let row = rows.get(usize::from(r))?;
        let (k, k2) = if alternate {
            (
                *col.get(1 + usize::from(r % 2))?,
                *row.get(1 + usize::from(c % 2))?,
            )
        } else {
            (*col.first()?, *row.first()?)
        };
        Some(grid.corners(cell, k, k2))
    };
    let mut arcs = Vec::new();
    for c in 1..=side {
        for r in 1..=side {
            let mut options: Vec<(Cell, Option<u32>, [Option<u32>; 2])> = Vec::new();
            if c < side {
                let one = corners((c, r), false);
                let here = corners((c, r), true);
                let next = corners((c + 1, r), true);
                if let (Some(one), Some(here), Some(next)) = (one, here, next) {
                    options.push(((c + 1, r), one[3], [here[1], next[2]]));
                }
            }
            if r < side {
                let one = corners((c, r), false);
                let here = corners((c, r), true);
                let above = corners((c, r + 1), true);
                if let (Some(one), Some(here), Some(above)) = (one, here, above) {
                    options.push(((c, r + 1), one[1], [here[3], above[0]]));
                }
            }
            for (other, x1, chain) in options {
                let (Some(x1), [Some(first), Some(second)]) = (x1, chain) else {
                    continue;
                };
                if !(grid.linked(first, second) && grid.linked(x1, first)) {
                    continue;
                }
                let horizontal = other.1 == r;
                let forward = if horizontal { r % 2 == 0 } else { c % 2 == 0 };
                let (tail, head) = if forward {
                    ((c, r), other)
                } else {
                    (other, (c, r))
                };
                arcs.push(RawArc {
                    tail,
                    head,
                    x1,
                    chain: [first, second],
                });
            }
        }
    }
    arcs
}

/// Drop arcs until every pair of arcs at a cell has spins that share a
/// coupler, for each commodity. Among a conflicting pair the later arc drops.
/// The passes repeat until one drops nothing.
fn prune(mut arcs: Vec<RawArc>, linked: impl Fn(u32, u32) -> bool) -> Vec<RawArc> {
    loop {
        let mut incident: BTreeMap<Cell, Vec<usize>> = BTreeMap::new();
        for (i, arc) in arcs.iter().enumerate() {
            incident.entry(arc.tail).or_default().push(i);
            incident.entry(arc.head).or_default().push(i);
        }
        let mut dropped: BTreeSet<usize> = BTreeSet::new();
        for (&v, ids) in &incident {
            for k in 0..2 {
                for (a, &i) in ids.iter().enumerate() {
                    for &j in ids.iter().skip(a + 1) {
                        if dropped.contains(&i) || dropped.contains(&j) {
                            continue;
                        }
                        if let (Some(first), Some(second)) = (arcs.get(i), arcs.get(j)) {
                            if !linked(first.spin(v, k), second.spin(v, k)) {
                                let _ = dropped.insert(i.max(j));
                            }
                        }
                    }
                }
            }
        }
        if dropped.is_empty() {
            return arcs;
        }
        arcs = arcs
            .into_iter()
            .enumerate()
            .filter(|(i, _)| !dropped.contains(i))
            .map(|(_, arc)| arc)
            .collect();
    }
}

/// Mark `v` as seen. `true` when it was not seen before.
fn mark(seen: &mut [bool], v: usize) -> bool {
    seen.get_mut(v)
        .is_some_and(|slot| !core::mem::replace(slot, true))
}

/// The list of neighbours of `v`.
fn neighbours(adjacency: &[Vec<usize>], v: usize) -> &[usize] {
    adjacency.get(v).map_or(&[], Vec::as_slice)
}

/// The nodes of the largest strongly connected component of the graph on
/// `n` nodes with directed `arcs`. Among components of equal size, the one
/// with the smallest node index wins. The result flags each node. `None` on
/// a counter overflow.
fn largest_component(n: usize, arcs: &[(usize, usize)]) -> Option<Vec<bool>> {
    let mut forward: Vec<Vec<usize>> = vec![Vec::new(); n];
    let mut backward: Vec<Vec<usize>> = vec![Vec::new(); n];
    for &(from, to) in arcs {
        if let Some(list) = forward.get_mut(from) {
            list.push(to);
        }
        if let Some(list) = backward.get_mut(to) {
            list.push(from);
        }
    }
    // Pass 1: finishing order on the forward graph.
    let mut seen = vec![false; n];
    let mut order: Vec<usize> = Vec::with_capacity(n);
    for start in 0..n {
        if !mark(&mut seen, start) {
            continue;
        }
        let mut stack: Vec<(usize, usize)> = vec![(start, 0)];
        while let Some(&(v, next)) = stack.last() {
            if let Some(&w) = neighbours(&forward, v).get(next) {
                if let Some(top) = stack.last_mut() {
                    top.1 = top.1.checked_add(1)?;
                }
                if mark(&mut seen, w) {
                    stack.push((w, 0));
                }
            } else {
                order.push(v);
                let _ = stack.pop();
            }
        }
    }
    // Pass 2: components on the backward graph, in reverse finishing order.
    let mut component = vec![usize::MAX; n];
    let mut count = 0usize;
    for &start in order.iter().rev() {
        if component.get(start) != Some(&usize::MAX) {
            continue;
        }
        if let Some(slot) = component.get_mut(start) {
            *slot = count;
        }
        let mut stack = vec![start];
        while let Some(v) = stack.pop() {
            for &w in neighbours(&backward, v) {
                if let Some(slot) = component.get_mut(w) {
                    if *slot == usize::MAX {
                        *slot = count;
                        stack.push(w);
                    }
                }
            }
        }
        count = count.checked_add(1)?;
    }
    let mut size = vec![0usize; count];
    let mut smallest = vec![usize::MAX; count];
    for (v, &id) in component.iter().enumerate() {
        if let Some(slot) = size.get_mut(id) {
            *slot = slot.checked_add(1)?;
        }
        if let Some(slot) = smallest.get_mut(id) {
            *slot = (*slot).min(v);
        }
    }
    let mut best: Option<usize> = None;
    for id in 0..count {
        let key = |i: usize| (size.get(i).copied(), smallest.get(i).copied());
        let better = best.is_none_or(|b| {
            let (sa, ma) = key(id);
            let (sb, mb) = key(b);
            sa > sb || (sa == sb && ma < mb)
        });
        if better {
            best = Some(id);
        }
    }
    Some(component.iter().map(|&id| Some(id) == best).collect())
}

/// An arc of the template: node indices and topology positions of the spins.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct Arc {
    tail: u32,
    head: u32,
    x1: u32,
    chain: [u32; 2],
}

/// The cells and arcs of the template, which does not depend on the nonce.
struct Template {
    cells: Vec<Cell>,
    arcs: Vec<Arc>,
}

/// The template of a topology. `None` when it has no arc, or on an internal
/// inconsistency.
fn template(grid: &Grid) -> Option<Template> {
    let (rows, cols) = layout(grid)?;
    let arcs = prune(raw_arcs(grid, &rows, &cols), |a, b| grid.linked(a, b));
    let ends: BTreeSet<Cell> = arcs.iter().flat_map(|arc| [arc.tail, arc.head]).collect();
    let nodes: Vec<Cell> = ends.into_iter().collect();
    let index = |cell: Cell| nodes.binary_search(&cell).ok();
    let edges = arcs
        .iter()
        .map(|arc| Some((index(arc.tail)?, index(arc.head)?)))
        .collect::<Option<Vec<(usize, usize)>>>()?;
    let in_core = largest_component(nodes.len(), &edges)?;
    let cells: Vec<Cell> = nodes
        .iter()
        .zip(&in_core)
        .filter(|(_, &keep)| keep)
        .map(|(&cell, _)| cell)
        .collect();
    let core = |cell: Cell| cells.binary_search(&cell).ok();
    let mut kept = Vec::new();
    for arc in &arcs {
        if let (Some(tail), Some(head)) = (core(arc.tail), core(arc.head)) {
            kept.push(Arc {
                tail: u32::try_from(tail).ok()?,
                head: u32::try_from(head).ok()?,
                x1: arc.x1,
                chain: arc.chain,
            });
        }
    }
    (!kept.is_empty()).then_some(Template { cells, arcs: kept })
}

/// Admission: the topology is a subgraph of the Zephyr lattice named by the
/// parameters, and its template has an arc (code 12 otherwise). A degree above
/// the limit is left to the size bounds (code 13).
fn check_topology(params: &Params<'_>, topology: &BaseTopology) -> bool {
    let Some(shape) = Shape::of(params) else {
        return false;
    };
    let ids = topology.node_ids();
    let zephyr_nodes = ids
        .iter()
        .all(|&id| zephyr_coordinates(shape.m, shape.t, id).is_some());
    let zephyr_edges = topology.edges().iter().all(|&(u, v)| {
        let at = |pos: u32| usize::try_from(pos).ok().and_then(|pos| ids.get(pos));
        matches!((at(u), at(v)), (Some(&a), Some(&b)) if zephyr_coupler(shape.m, shape.t, a, b))
    });
    zephyr_nodes && zephyr_edges && template(&Grid::new(shape, topology)).is_some()
}

/// The unit-capacity maximum flow from `sources` to `sinks` over the arcs
/// reaches `sources.len()`. A failed index or overflow is not a route.
fn routes(n: usize, arcs: &[Arc], sources: &[usize], sinks: &[usize]) -> bool {
    max_flow(n, arcs, sources, sinks) == Some(sources.len())
}

/// The value of the unit-capacity maximum flow, found by breadth-first
/// augmenting paths. `None` on an index or counter overflow.
fn max_flow(n: usize, arcs: &[Arc], sources: &[usize], sinks: &[usize]) -> Option<usize> {
    let source = n;
    let sink = n.checked_add(1)?;
    let total = n.checked_add(2)?;
    let mut to: Vec<usize> = Vec::new();
    let mut capacity: Vec<u8> = Vec::new();
    let mut adjacent: Vec<Vec<usize>> = vec![Vec::new(); total];
    let mut add = |from: usize, into: usize| -> Option<()> {
        let forward = to.len();
        let backward = forward.checked_add(1)?;
        to.push(into);
        capacity.push(1);
        to.push(from);
        capacity.push(0);
        adjacent.get_mut(from)?.push(forward);
        adjacent.get_mut(into)?.push(backward);
        Some(())
    };
    for arc in arcs {
        add(
            usize::try_from(arc.tail).ok()?,
            usize::try_from(arc.head).ok()?,
        )?;
    }
    for &v in sources {
        add(source, v)?;
    }
    for &v in sinks {
        add(v, sink)?;
    }
    let mut flow = 0usize;
    loop {
        // Breadth-first search for an augmenting path, by arrival edge.
        let mut arrival: Vec<Option<usize>> = vec![None; total];
        let mut seen = vec![false; total];
        let _ = mark(&mut seen, source);
        let mut queue = alloc::collections::VecDeque::from([source]);
        while let Some(v) = queue.pop_front() {
            for &edge in neighbours(&adjacent, v) {
                let (&next, &room) = (to.get(edge)?, capacity.get(edge)?);
                if room > 0 && mark(&mut seen, next) {
                    *arrival.get_mut(next)? = Some(edge);
                    queue.push_back(next);
                }
            }
        }
        if seen.get(sink) != Some(&true) {
            return Some(flow);
        }
        let mut at = sink;
        while at != source {
            let edge = (*arrival.get(at)?)?;
            *capacity.get_mut(edge)? = 0;
            *capacity.get_mut(edge ^ 1)? = 1;
            at = *to.get(edge ^ 1)?;
        }
        flow = flow.checked_add(1)?;
    }
}

/// An arc of an instance: node indices, instance positions of the spins, and
/// the costs of the two commodities.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct ArcRecord {
    tail: u32,
    head: u32,
    x1: u32,
    chain: [u32; 2],
    cost: [u16; 2],
}

impl ArcRecord {
    /// The spin of commodity `k` inside the K4 of the node `v`.
    fn spin(&self, v: u32, k: usize) -> u32 {
        if k == 0 {
            self.x1
        } else if v == self.tail.min(self.head) {
            self.chain[0]
        } else {
            self.chain[1]
        }
    }
}

/// The energy in `x = (1 - s) / 2` form, in quarter-milli, while it is built.
struct Quarter {
    h: Vec<i64>,
    j: BTreeMap<(u32, u32), i64>,
    offset: i64,
}

impl Quarter {
    /// `c * x_i`.
    fn lin(&mut self, i: u32, c: i64) -> Option<()> {
        let field = self.h.get_mut(usize::try_from(i).ok()?)?;
        *field = field.checked_sub(c.checked_mul(2)?)?;
        self.offset = self.offset.checked_add(c.checked_mul(2)?)?;
        Some(())
    }

    /// `c * x_i * x_j`.
    fn pair(&mut self, i: u32, j: u32, c: i64) -> Option<()> {
        if i == j {
            return None;
        }
        let key = (i.min(j), i.max(j));
        let entry = self.j.entry(key).or_insert(0);
        *entry = entry.checked_add(c)?;
        for end in [i, j] {
            let field = self.h.get_mut(usize::try_from(end).ok()?)?;
            *field = field.checked_sub(c)?;
        }
        self.offset = self.offset.checked_add(c)?;
        Some(())
    }

    /// `w * (sum of c_i x_i + b0)^2`.
    fn square(&mut self, w: i64, coeffs: &[(u32, i64)], b0: i64) -> Option<()> {
        for (a, &(i, ci)) in coeffs.iter().enumerate() {
            let linear = ci
                .checked_mul(ci)?
                .checked_add(b0.checked_mul(ci)?.checked_mul(2)?)?;
            self.lin(i, w.checked_mul(linear)?)?;
            for &(j, cj) in coeffs.iter().skip(a + 1) {
                self.pair(i, j, w.checked_mul(2)?.checked_mul(ci)?.checked_mul(cj)?)?;
            }
        }
        let constant = w.checked_mul(4)?.checked_mul(b0.checked_mul(b0)?)?;
        self.offset = self.offset.checked_add(constant)?;
        Some(())
    }
}

/// The Ising form of a routing energy.
struct Ising {
    h: Vec<i32>,
    edges: Vec<(u32, u32)>,
    j: Vec<i32>,
    offset_milli: i64,
    strength: i64,
}

/// Exact division by four, `None` with a remainder.
fn quarter_to_milli(value: i64) -> Option<i64> {
    (value % 4 == 0).then_some(value / 4)
}

/// The energy of a routing instance over `n` spins: conservation squares per
/// node and commodity, the capacity and cost terms per arc, and the chain
/// couplers. `None` for an out of range index, an overflow, or a coefficient
/// that is not an integer in milli.
fn build_energy(n: usize, supply: &[[i8; 2]], arcs: &[ArcRecord]) -> Option<Ising> {
    let mut energy = Quarter {
        h: vec![0; n],
        j: BTreeMap::new(),
        offset: 0,
    };
    for (v, supplies) in (0u32..).zip(supply) {
        for (k, &b) in supplies.iter().enumerate() {
            let mut coeffs: Vec<(u32, i64)> = Vec::new();
            for arc in arcs {
                if arc.tail == v {
                    coeffs.push((arc.spin(v, k), 1));
                }
                if arc.head == v {
                    coeffs.push((arc.spin(v, k), -1));
                }
            }
            if !coeffs.is_empty() {
                energy.square(CONSERVE, &coeffs, -i64::from(b))?;
            }
        }
    }
    for arc in arcs {
        energy.pair(arc.x1, *arc.chain.first()?, CAPACITY)?;
        energy.lin(arc.x1, i64::from(arc.cost[0]))?;
        energy.lin(*arc.chain.first()?, i64::from(arc.cost[1]))?;
    }

    let mut couplings: BTreeMap<(u32, u32), i64> = BTreeMap::new();
    for (&key, &value) in &energy.j {
        let _ = couplings.insert(key, quarter_to_milli(value)?);
    }
    let h = energy
        .h
        .iter()
        .map(|&value| quarter_to_milli(value))
        .collect::<Option<Vec<i64>>>()?;
    let offset_milli = quarter_to_milli(energy.offset)?;

    let mut local = vec![0i64; n];
    for (&(i, j), &value) in &couplings {
        for end in [i, j] {
            let slot = local.get_mut(usize::try_from(end).ok()?)?;
            *slot = slot.checked_add(value.checked_abs()?)?;
        }
    }
    let mut strength = 0i64;
    for arc in arcs {
        for &spin in &arc.chain {
            let at = usize::try_from(spin).ok()?;
            let load = local.get(at)?.checked_add(h.get(at)?.checked_abs()?)?;
            strength = strength.max(load);
        }
    }
    let strength = strength.checked_add(1)?;
    for arc in arcs {
        let [first, second] = arc.chain;
        let entry = couplings
            .entry((first.min(second), first.max(second)))
            .or_insert(0);
        *entry = entry.checked_sub(strength)?;
    }

    let mut edges = Vec::new();
    let mut j = Vec::new();
    for (&key, &value) in &couplings {
        if value != 0 {
            edges.push(key);
            j.push(i32::try_from(value).ok()?);
        }
    }
    Some(Ising {
        h: h.into_iter()
            .map(|value| i32::try_from(value).ok())
            .collect::<Option<Vec<i32>>>()?,
        edges,
        j,
        offset_milli,
        strength,
    })
}

/// The terminal nodes of the try drawn from `order`: for each commodity,
/// `pairs` sources and `pairs` sinks, taken from consecutive entries.
fn terminals(order: &[u32], pairs: usize) -> Option<[(Vec<usize>, Vec<usize>); 2]> {
    let mut found: [(Vec<usize>, Vec<usize>); 2] = Default::default();
    let mut entries = order.iter().map(|&v| usize::try_from(v).ok());
    for (sources, sinks) in &mut found {
        for _ in 0..pairs {
            sources.push(entries.next()??);
            sinks.push(entries.next()??);
        }
    }
    Some(found)
}

/// The supplies of each node and commodity. Each try shuffles the node
/// indices on the `terminal` stream, which continues across tries, and ends
/// when both commodities route alone. After [`TERMINAL_TRIES`] tries the salt
/// gives code 14.
fn draw_supply(
    streams: &mut Streams<'_>,
    template: &Template,
    pairs: usize,
) -> Result<Vec<[i8; 2]>, Code> {
    let n_nodes = template.cells.len();
    let count = u32::try_from(n_nodes).map_err(|_| Code::BoundsExceeded)?;
    let mut stream = streams.open(TERMINAL).ok_or(Code::NoInstance)?;
    for _ in 0..TERMINAL_TRIES {
        let mut order: Vec<u32> = (0..count).collect();
        shuffle(&mut stream, &mut order)?;
        let picked = terminals(&order, pairs).ok_or(Code::TopologyIncompatible)?;
        if !picked
            .iter()
            .all(|(sources, sinks)| routes(n_nodes, &template.arcs, sources, sinks))
        {
            continue;
        }
        let mut supply = vec![[0i8; 2]; n_nodes];
        for (k, (sources, sinks)) in picked.iter().enumerate() {
            for (nodes, value) in [(sources, 1i8), (sinks, -1)] {
                for &v in nodes {
                    *supply
                        .get_mut(v)
                        .and_then(|pair| pair.get_mut(k))
                        .ok_or(Code::TopologyIncompatible)? = value;
                }
            }
        }
        return Ok(supply);
    }
    Err(Code::NoInstance)
}

/// The costs of both commodities for each arc: a `cost` stream draw of 0 is
/// 62 and a draw of 1 is 124.
fn draw_costs(streams: &mut Streams<'_>, arcs: usize) -> Result<Vec<[u16; 2]>, Code> {
    let two = NonZeroU32::MIN.saturating_add(1);
    let mut stream = streams.open(COST).ok_or(Code::NoInstance)?;
    let mut costs: Vec<[u16; 2]> = Vec::with_capacity(arcs);
    for _ in 0..arcs {
        let mut pair = [0u16; 2];
        for slot in &mut pair {
            let pick = usize::try_from(uniform(&mut stream, two))
                .map_err(|_| Code::TopologyIncompatible)?;
            *slot = *COSTS.get(pick).ok_or(Code::TopologyIncompatible)?;
        }
        costs.push(pair);
    }
    Ok(costs)
}

fn generate(
    params: &Params<'_>,
    topology: &BaseTopology,
    streams: &mut Streams<'_>,
) -> Result<InstanceBody, Code> {
    let defect = Code::TopologyIncompatible;
    let shape = Shape::of(params).ok_or(Code::ParamsMalformed)?;
    let grid = Grid::new(shape, topology);
    let template = template(&grid).ok_or(defect)?;
    let pairs = template.cells.len() / shape.divisor;
    let supply = draw_supply(streams, &template, pairs)?;
    let costs = draw_costs(streams, template.arcs.len())?;

    // The instance nodes: every arc spin, in topology order.
    let mut spins: Vec<u32> = template
        .arcs
        .iter()
        .flat_map(|arc| [arc.x1, arc.chain[0], arc.chain[1]])
        .collect();
    spins.sort_unstable();
    let total = spins.len();
    spins.dedup();
    if spins.len() != total {
        return Err(defect);
    }
    let place = |pos: u32| -> Result<u32, Code> {
        let at = spins.binary_search(&pos).map_err(|_| defect)?;
        u32::try_from(at).map_err(|_| Code::BoundsExceeded)
    };
    let mut records: Vec<ArcRecord> = Vec::with_capacity(template.arcs.len());
    for (arc, &cost) in template.arcs.iter().zip(&costs) {
        records.push(ArcRecord {
            tail: arc.tail,
            head: arc.head,
            x1: place(arc.x1)?,
            chain: [place(arc.chain[0])?, place(arc.chain[1])?],
            cost,
        });
    }
    let ising = build_energy(spins.len(), &supply, &records).ok_or(defect)?;
    // No street cell configuration reaches the cap (see the unit test
    // `chain_strength_never_reaches_the_cap`), so a salt gives code 13 here
    // only for a template outside the pinned construction.
    if ising.strength > MAX_STRENGTH {
        return Err(Code::BoundsExceeded);
    }
    for &(i, j) in &ising.edges {
        let at = |pos: u32| usize::try_from(pos).ok().and_then(|pos| spins.get(pos));
        match (at(i), at(j)) {
            (Some(&a), Some(&b)) if grid.linked(a, b) => {}
            _ => return Err(defect),
        }
    }
    let node_ids = spins
        .iter()
        .map(|&pos| {
            usize::try_from(pos)
                .ok()
                .and_then(|pos| topology.node_ids().get(pos).copied())
                .ok_or(defect)
        })
        .collect::<Result<Vec<u32>, Code>>()?;
    let strength = u16::try_from(ising.strength).map_err(|_| Code::BoundsExceeded)?;
    let metadata = metadata_region(&template.cells, &supply, &records, strength)?;
    Ok(InstanceBody {
        node_ids,
        edges: ising.edges,
        h: ising.h,
        j: ising.j,
        offset_milli: ising.offset_milli,
        metadata,
    })
}

/// The metadata region: the routing section (kind 7).
fn metadata_region(
    cells: &[Cell],
    supply: &[[i8; 2]],
    arcs: &[ArcRecord],
    strength: u16,
) -> Result<Vec<u8>, Code> {
    let overflow = Code::BoundsExceeded;
    let mut payload = u32::try_from(cells.len())
        .map_err(|_| overflow)?
        .to_le_bytes()
        .to_vec();
    for (&(c, r), supplies) in cells.iter().zip(supply) {
        payload.extend_from_slice(&c.to_le_bytes());
        payload.extend_from_slice(&r.to_le_bytes());
        payload.extend(supplies.iter().map(|&b| b.to_le_bytes()[0]));
    }
    payload.extend_from_slice(
        &u32::try_from(arcs.len())
            .map_err(|_| overflow)?
            .to_le_bytes(),
    );
    for arc in arcs {
        for word in [arc.tail, arc.head, arc.x1, arc.chain[0], arc.chain[1]] {
            payload.extend_from_slice(&word.to_le_bytes());
        }
        for cost in arc.cost {
            payload.extend_from_slice(&cost.to_le_bytes());
        }
    }
    payload.extend_from_slice(&strength.to_le_bytes());
    region(&[(KIND_ROUTING, payload)])
}

/// The decoded routing section.
struct Decoded {
    supply: Vec<[i8; 2]>,
    arcs: Vec<ArcRecord>,
    strength: u16,
}

/// Whether an arc from `tail` to `head` follows the street pattern: horizontal arcs point right in even rows and left in odd
/// rows, vertical arcs point up in even columns and down in odd columns.
fn street_direction(tail: Cell, head: Cell) -> bool {
    let (low, high, forward) = if tail.1 == head.1 {
        // Horizontal: the pair is `(c, r)` and `(c + 1, r)`.
        (tail.min(head), tail.max(head), tail.1.is_multiple_of(2))
    } else if tail.0 == head.0 {
        // Vertical: the pair is `(c, r)` and `(c, r + 1)`.
        (tail.min(head), tail.max(head), tail.0.is_multiple_of(2))
    } else {
        return false;
    };
    let adjacent = if tail.1 == head.1 {
        low.0.checked_add(1) == Some(high.0)
    } else {
        low.1.checked_add(1) == Some(high.1)
    };
    adjacent && (forward == (tail == low))
}

/// The routing section when its layout and structural rules hold: cells,
/// supplies, arcs, costs, and strength. The energy is not checked here.
fn decode(params: &Params<'_>, instance: &Instance) -> Option<Decoded> {
    let shape = Shape::of(params)?;
    let [payload] = sections(instance.metadata(), [KIND_ROUTING])?;
    let mut reader = Reader::new(payload);
    let n_nodes = usize::try_from(reader.u32()?).ok()?;
    if n_nodes == 0 || reader.rest().len() < n_nodes.checked_mul(NODE_RECORD)? {
        return None;
    }
    let mut cells: Vec<Cell> = Vec::with_capacity(n_nodes);
    let mut supply: Vec<[i8; 2]> = Vec::with_capacity(n_nodes);
    for _ in 0..n_nodes {
        let cell = (reader.u16()?, reader.u16()?);
        let &[first, second] = reader.take(2)? else {
            return None;
        };
        let (first, second) = (i8::from_le_bytes([first]), i8::from_le_bytes([second]));
        let in_grid = (1..=shape.side).contains(&cell.0) && (1..=shape.side).contains(&cell.1);
        let ascending = cells.last().is_none_or(|&last| cell_lt(last, cell));
        let supplies_ok = [first, second].iter().all(|b| (-1..=1).contains(b));
        if !(in_grid && ascending && supplies_ok) {
            return None;
        }
        cells.push(cell);
        supply.push([first, second]);
    }
    let n_arcs = usize::try_from(reader.u32()?).ok()?;
    let arc_bytes = n_arcs.checked_mul(ARC_RECORD)?.checked_add(2)?;
    if n_arcs == 0 || reader.rest().len() != arc_bytes {
        return None;
    }
    let mut arcs: Vec<ArcRecord> = Vec::with_capacity(n_arcs);
    let mut joined: BTreeSet<(u32, u32)> = BTreeSet::new();
    for _ in 0..n_arcs {
        let tail = reader.u32()?;
        let head = reader.u32()?;
        let x1 = reader.u32()?;
        let chain = [reader.u32()?, reader.u32()?];
        let cost = [reader.u16()?, reader.u16()?];
        let end = |v: u32| cells.get(usize::try_from(v).ok()?).copied();
        if !street_direction(end(tail)?, end(head)?)
            || !joined.insert((tail.min(head), tail.max(head)))
            || !cost.iter().all(|c| COSTS.contains(c))
        {
            return None;
        }
        arcs.push(ArcRecord {
            tail,
            head,
            x1,
            chain,
            cost,
        });
    }
    let strength = reader.u16()?;
    let n_spins = instance.node_ids().len();
    if n_arcs.checked_mul(3)? != n_spins || !(1..=1000).contains(&strength) {
        return None;
    }
    let mut used = vec![false; n_spins];
    for arc in &arcs {
        for spin in [arc.x1, arc.chain[0], arc.chain[1]] {
            if !mark(&mut used, usize::try_from(spin).ok()?) {
                return None;
            }
        }
    }
    let pairs = n_nodes.checked_div(shape.divisor)?;
    for k in 0..2 {
        let count = |wanted: i8| {
            supply
                .iter()
                .filter(|pair| pair.get(k) == Some(&wanted))
                .count()
        };
        if count(1) != pairs || count(-1) != pairs {
            return None;
        }
    }
    if supply.iter().any(|pair| pair.iter().all(|&b| b != 0)) {
        return None;
    }
    Some(Decoded {
        supply,
        arcs,
        strength,
    })
}

fn check_metadata(params: &Params<'_>, instance: &Instance) -> bool {
    check_instance(params, instance).is_some()
}

/// The decoded section when the instance is a valid routing instance: the
/// structural rules hold and the energy rebuilt from the section is the
/// energy of the instance, chain strength included.
fn check_instance(params: &Params<'_>, instance: &Instance) -> Option<Decoded> {
    let decoded = decode(params, instance)?;
    let ising = build_energy(instance.node_ids().len(), &decoded.supply, &decoded.arcs)?;
    let same = ising.h == instance.h()
        && ising.edges == instance.edges()
        && ising.j == instance.j()
        && ising.offset_milli == instance.offset_milli()
        && ising.strength == i64::from(decoded.strength);
    same.then_some(decoded)
}

/// What a spin state does with the routing constraints. Information only.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct RoutingDefects {
    /// Arcs where both commodities are on.
    pub capacity_conflicts: u32,
    /// Pairs of a node and a commodity where outflow minus inflow differs from
    /// the supply.
    pub conservation_violations: u32,
    /// The number of arcs each commodity uses.
    pub used_arcs: [u32; 2],
    /// Arcs whose two chain spins differ.
    pub broken_chains: u32,
}

/// The routing defects of a spin state of the instance, with
/// `x = (1 - s) / 2`. Commodity 1 uses `x[x1]` and commodity 2 uses
/// `x[chain0]`. `None` for an instance that fails the family validation, or a
/// state of the wrong length or with a value other than `+1` or `-1`. This is
/// information only and never part of acceptance (FAM-40).
#[must_use]
pub fn routing_defects(
    params: &Params<'_>,
    instance: &Instance,
    spins: &[i8],
) -> Option<RoutingDefects> {
    let decoded = check_instance(params, instance)?;
    if spins.len() != instance.node_ids().len() || spins.iter().any(|&s| s != 1 && s != -1) {
        return None;
    }
    let on = |pos: u32| -> Option<i64> {
        let spin = *spins.get(usize::try_from(pos).ok()?)?;
        Some(i64::from(spin == -1))
    };
    let mut result = RoutingDefects {
        capacity_conflicts: 0,
        conservation_violations: 0,
        used_arcs: [0; 2],
        broken_chains: 0,
    };
    let mut net = vec![[0i64; 2]; decoded.supply.len()];
    for arc in &decoded.arcs {
        let bits = [on(arc.x1)?, on(*arc.chain.first()?)?];
        if on(*arc.chain.get(1)?)? != bits[1] {
            result.broken_chains = result.broken_chains.checked_add(1)?;
        }
        if bits[0] == 1 && bits[1] == 1 {
            result.capacity_conflicts = result.capacity_conflicts.checked_add(1)?;
        }
        for (k, &bit) in bits.iter().enumerate() {
            if bit == 1 {
                let used = result.used_arcs.get_mut(k)?;
                *used = used.checked_add(1)?;
            }
            let tail = net.get_mut(usize::try_from(arc.tail).ok()?)?.get_mut(k)?;
            *tail = tail.checked_add(bit)?;
            let head = net.get_mut(usize::try_from(arc.head).ok()?)?.get_mut(k)?;
            *head = head.checked_sub(bit)?;
        }
    }
    for (flow, supplies) in net.iter().zip(&decoded.supply) {
        for (&balance, &wanted) in flow.iter().zip(supplies) {
            if balance != i64::from(wanted) {
                result.conservation_violations = result.conservation_violations.checked_add(1)?;
            }
        }
    }
    Some(result)
}

