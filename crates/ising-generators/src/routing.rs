    /// end of those two arcs and the smaller end of the other two. `costs`
    /// gives the two costs of each present arc and `b` is the supply of the
    /// cell for commodity 2.
    fn local_strength(
        present: usize,
        row: usize,
        column: usize,
        costs: usize,
        b: i8,
    ) -> Option<i64> {
        // Leaves 0 and 1 are the larger-end neighbours, so the cell is node 2.
        let centre = 2u32;
        let mut supply = vec![[0i8; 2]; 7];
        supply.get_mut(2)?[1] = b;
        let mut arcs = Vec::new();
        for side in 0..4usize {
            if present >> side & 1 == 0 {
                continue;
            }
            // Left, right, below, above: the cell is the larger end for 0 and 2.
            let larger = side % 2 == 0;
            let leaf = if larger { side / 2 } else { 3 + side / 2 };
            let leaf = u32::try_from(leaf).ok()?;
            let outward = match side {
                0 => row == 1,
                1 => row == 0,
                2 => column == 1,
                _ => column == 0,
            };
            let (tail, head) = if outward {
                (centre, leaf)
            } else {
                (leaf, centre)
            };
            let at = u32::try_from(arcs.len()).ok()?;
            arcs.push(ArcRecord {
                tail,
                head,
                x1: 3 * at,
                chain: [3 * at + 1, 3 * at + 2],
                cost: [
                    COSTS[costs >> (2 * side) & 1],
                    COSTS[costs >> (2 * side + 1) & 1],
                ],
            });
        }
        build_energy(3 * arcs.len(), &supply, &arcs).map(|ising| ising.strength)
    }

    /// No cell configuration gives a chain strength above 1000, so the cap of
    /// code 13 cannot trigger. The chain spins of a cell sit in the squares of
    /// that cell only, so the strength depends on the street arcs of one cell,
    /// their costs, and the supply.
    #[test]
    fn chain_strength_never_reaches_the_cap() {
        let mut most = 0;
        for present in 1..16usize {
            for row in 0..2 {
                for column in 0..2 {
                    for costs in 0..256usize {
                        for b in [-1i8, 0, 1] {
                            let strength =
                                local_strength(present, row, column, costs, b).expect("energy");
                            most = most.max(strength);
                        }
                    }
                }
            }
        }
        assert!(most <= MAX_STRENGTH, "largest strength {most}");
        assert!(most >= 931, "the live template reaches 931, got {most}");
    }

    fn arc(tail: Cell, head: Cell, x1: u32, chain: [u32; 2]) -> RawArc {
        RawArc {
            tail,
            head,
            x1,
            chain,
        }
    }

    /// The arcs that stay, as `x1` spins, after pruning with the couplers
    /// `pairs`.
    fn survivors(arcs: Vec<RawArc>, pairs: &[(u32, u32)]) -> Vec<u32> {
        let linked = |a: u32, b: u32| pairs.contains(&(a.min(b), a.max(b)));
        prune(arcs, linked).iter().map(|arc| arc.x1).collect()
    }

    /// Three arcs meet at the cell (2, 2). The commodity 1 spins of the first
    /// and second arc share no coupler, and neither do the second and third.
    /// The first pair drops the second arc. The second pair is then moot, so
    /// the third arc stays.
    #[test]
    fn pruning_drops_the_later_arc_and_repeats() {
        let centre = (2, 2);
        let arcs = vec![
            arc((1, 2), centre, 1, [2, 3]),
            arc(centre, (3, 2), 4, [5, 6]),
            arc(centre, (2, 3), 7, [8, 9]),
        ];
        // Commodity 2 spins at the cell: 3 (larger end), 5 and 8 (smaller end).
        let chains = [(3, 5), (3, 8), (5, 8)];
        let mut couplers = chains.to_vec();
        couplers.push((1, 7));
        assert_eq!(survivors(arcs.clone(), &couplers), vec![1, 7]);

        // A conflict between the commodity 2 spins drops the later arc too.
        let mut couplers = vec![(1, 4), (1, 7), (4, 7), (3, 5), (3, 8)];
        assert_eq!(survivors(arcs.clone(), &couplers), vec![1, 4]);
        couplers.push((5, 8));
        assert_eq!(survivors(arcs.clone(), &couplers), vec![1, 4, 7]);

        // Nothing drops when every pair is linked.
        let all = [(1, 4), (1, 7), (4, 7), (3, 5), (3, 8), (5, 8)];
        assert_eq!(survivors(arcs, &all), vec![1, 4, 7]);
    }

    /// The later arc of a conflicting pair drops, at either end of the pair.
    #[test]
    fn pruning_drops_the_arc_that_is_later_in_the_list() {
        let arcs = vec![
            arc((1, 1), (2, 1), 1, [2, 3]),
            arc((2, 1), (3, 1), 4, [5, 6]),
            arc((1, 1), (1, 2), 7, [8, 9]),
        ];
        // Cell (2, 1) pairs spins 1 and 4, then 3 and 5. Cell (1, 1) pairs
        // spins 1 and 7, then 2 and 8.
        assert_eq!(
            survivors(arcs.clone(), &[(1, 7), (3, 5), (2, 8)]),
            vec![1, 7]
        );
        assert_eq!(
            survivors(arcs.clone(), &[(1, 4), (3, 5), (2, 8)]),
            vec![1, 4]
        );
        assert_eq!(
            survivors(arcs.clone(), &[(1, 4), (1, 7), (3, 5)]),
            vec![1, 4]
        );
        assert_eq!(survivors(arcs, &[(1, 4), (1, 7), (2, 8)]), vec![1, 7]);
    }

    #[test]
    fn flow_routes_units_through_unit_arcs() {
        let arc = |tail, head| Arc {
            tail,
            head,
            x1: 0,
            chain: [0, 0],
        };
        let path = [arc(0, 1), arc(1, 2), arc(2, 3)];
        assert!(routes(4, &path, &[0], &[3]));
        assert!(routes(4, &path, &[], &[]));
        assert!(!routes(4, &path, &[3], &[0]), "against the arcs");
        // Two units cannot share the arc 1 -> 2.
        let narrow = [arc(0, 1), arc(4, 1), arc(1, 2), arc(2, 3), arc(2, 5)];
        assert!(!routes(6, &narrow, &[0, 4], &[3, 5]));
        assert!(routes(6, &narrow, &[0], &[3]));
        // A second arc out of the shared cell makes both units feasible.
        let wide = [arc(0, 1), arc(4, 1), arc(1, 2), arc(1, 5)];
        assert!(routes(6, &wide, &[0, 4], &[2, 5]));
    }

