def render(doc: dict) -> str:
    return json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def _ev(*ids: str) -> list[str]:
    unknown = (
        set(ids)
        - set(EVIDENCE["provided"])
        - {item["id"] for item in EVIDENCE["partial"]}
    )
    if unknown:
        raise ValueError(f"unknown evidence id: {sorted(unknown)}")
    return [f"SC-2:{i}" for i in sorted(set(ids))]


def _case(name: str, evidence: list[str], **fields: object) -> dict:
    return {"name": name, "evidence": evidence, **fields}


