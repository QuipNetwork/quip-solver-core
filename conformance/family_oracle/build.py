def _params_cases() -> list[dict]:
    cases = []
    for name, schema, data, planned, evidence in _params_rows():
        code, values = decode_params(schema, data)
        if code != planned:
            raise ValueError(f"params case {name}: oracle code {code}, plan {planned}")
        cases.append(
            _case(
                name,
                _ev(*evidence),
                family_id=schema.family_id,
                revision=schema.revision,
                params_hex=data.hex(),
                expected_code=code,
                values=None if values is None else _values_json(schema, values),
                params_digest=None if code is not None else params_digest(data).hex(),
            )
        )
    return cases


def _params_by_name(name: str) -> bytes:
    for row_name, _, data, _, _ in _params_rows():
        if row_name == name:
            return data
    raise KeyError(name)


