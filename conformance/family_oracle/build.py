def _lease_nonce(name: str, index: int) -> bytes:
    for lease_name, start, count in _LEASES:
        if lease_name == name:
            result = lease_salts(_HASH_A, _HASH_B, _BASE_SALT, start, count)
            if result is None:
                raise ValueError(name)
            return result[index][2]
    raise KeyError(name)


