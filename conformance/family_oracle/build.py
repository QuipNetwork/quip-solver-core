    case = json.loads((_VECTORS_DIR / file).read_text())[section][index]
    digest = blake3.blake3(canonical_json(case).encode("ascii")).hexdigest()
    return _case(
        f"{file.removesuffix('.json')}/{section}/{index}",
        evidence,
        file=file,
        section=section,
        index=index,
        case_blake3=digest,
        generator=_GENERATOR,
    )


